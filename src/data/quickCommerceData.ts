/**
 * Converts a QuickCommerceItem to the internal MenuItem format
 * so it interfaces seamlessly with the existing cart, coupon, and checkout pipeline!
 */
export function quickCommerceItemToMenuItem(
  qc: QuickCommerceItem,
  selectedVariant?: QuickCommerceVariant
): MenuItem {
  const variant =
    selectedVariant ||
    (qc.selectedVariantId
      ? qc.variants?.find((v) => v.id === qc.selectedVariantId)
      : qc.variants?.find((v) => v.isDefault) || qc.variants?.[0]);

  const unit = variant ? variant.unit : qc.unit;
  const price = variant ? variant.price : qc.price;
  const originalPrice = variant?.originalPrice !== undefined ? variant.originalPrice : qc.originalPrice;
  const inStock = variant?.inStock !== undefined ? variant.inStock : qc.inStock;
  const stockCount = variant?.stockCount !== undefined ? variant.stockCount : (qc.stockCount || 50);
  const id = variant ? `${qc.id}__${variant.id}` : qc.id;

  return {
    id,
    restaurantId: 'likart-mart-hub-01',
    name: `${qc.name} (${unit})`,
    description: qc.description,
    price,
    originalPrice,
    category: qc.category,
    image: qc.image,
    isVeg: qc.isVeg,
    isBestseller: qc.isBestseller,
    isAvailable: inStock,
    rating: qc.rating,
    hasStockTracking: true,
    stockQuantity: stockCount,
  };
}

